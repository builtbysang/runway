/**
 * Runway — Doc Agent
 * Context → Claude drafts Project Brief or PRD → pushes to Notion
 */
import { draftDocument, DocType } from '@/skills/claude'
import { markdownToBlocks, createNotionPage, callout, divider } from '@/skills/notion'

export async function runDocAgent(opts: {
  context: string             // raw input: idea, notes, bullet points, anything
  docType: DocType            // 'brief' | 'prd'
  notionParentId: string      // Notion page ID or database ID
  notionParentType?: 'page' | 'database'
}): Promise<{ notionUrl: string; title: string; docType: DocType }> {
  const parentType = opts.notionParentType ?? 'page'

  console.log(`[Doc Agent] Drafting ${opts.docType} with Claude…`)
  const draft = await draftDocument({ context: opts.context, docType: opts.docType })

  console.log(`[Doc Agent] Converting to Notion blocks…`)
  const contentBlocks = markdownToBlocks(draft.markdown)

  // Prepend a callout banner so it's clear this was auto-generated
  const label = opts.docType === 'brief' ? 'Project Brief' : 'PRD'
  const banner = callout(
    `Auto-generated by Runway on ${new Date().toLocaleDateString('en-US', { dateStyle: 'medium' })}. Review and update before sharing.`,
    '🤖'
  )

  const blocks = [banner, divider(), ...contentBlocks]

  console.log(`[Doc Agent] Pushing to Notion (${blocks.length} blocks)…`)
  const page = await createNotionPage({
    parentId: opts.notionParentId,
    parentType,
    title: draft.title,
    blocks,
  })

  console.log(`[Doc Agent] Done → ${page.url}`)
  return { notionUrl: page.url, title: draft.title, docType: draft.docType }
}
